/*
 * Exercise pictograms (assets/program/art.json, generated by tools/gen_art.py): a posed figure in the
 * theme accent with equipment in neutral greys, looping smoothly between two key frames.
 */

/** A point that is either fixed or follows a joint (with an offset). */
sealed interface Pt {
    data class Abs(val x: Float, val y: Float) : Pt
    data class Joint(val name: String, val dx: Float, val dy: Float) : Pt
}

enum class Layer { BACK, MID, FRONT }
enum class Ink { GEAR, GEAR2, ACCENT }

sealed interface Gear {
    val layer: Layer
    val ink: Ink
    data class Line(val a: Pt, val b: Pt, val w: Float, override val ink: Ink, override val layer: Layer) : Gear
    data class Disc(val at: Pt, val r: Float, override val ink: Ink, override val layer: Layer) : Gear
    data class Ring(val at: Pt, val r: Float, val w: Float, override val ink: Ink, override val layer: Layer) : Gear
    data class Kettlebell(val at: Pt, val r: Float, override val ink: Ink, override val layer: Layer) : Gear
    data class Rect(val x: Float, val y: Float, val w: Float, val h: Float, val r: Float, override val ink: Ink, override val layer: Layer) : Gear
    data class Pill(val at: Pt, val w: Float, val h: Float, override val ink: Ink, override val layer: Layer) : Gear
    data class Poly(val a: List<Offset>, val b: List<Offset>?, override val ink: Ink, override val layer: Layer) : Gear
}

class Art(
    val frames: List<Map<String, Offset>>,
    val gear: List<Gear>,
    val front: Boolean,
    val floor: Boolean,
)

object ArtLibrary {
    @Volatile private var cache: Map<String, Art>? = null

    fun get(context: Context): Map<String, Art> = cache ?: synchronized(this) {
        cache ?: parse(context.applicationContext.assets.open("program/art.json").bufferedReader().use { it.readText() }).also { cache = it }
    }

    fun parse(text: String): Map<String, Art> {
        val root = Json.parseToJsonElement(text).jsonObject
        return root.mapValues { (_, v) -> art(v.jsonObject) }
    }

    private fun art(o: JsonObject): Art {
        val frames = o.getValue("frames").jsonArray.map { f ->
            f.jsonObject.mapValues { (_, p) -> p.jsonArray.let { Offset(it[0].jsonPrimitive.float, it[1].jsonPrimitive.float) } }
        }
        val gear = o.getValue("gear").jsonArray.mapNotNull { gear(it.jsonObject) }
        return Art(frames, gear, o["front"]?.jsonPrimitive?.boolean ?: false, o["floor"]?.jsonPrimitive?.boolean ?: true)
    }

    private fun pt(e: JsonElement): Pt = when (e) {
        is JsonPrimitive -> Pt.Joint(e.content, 0f, 0f)
        is JsonArray -> if (e[0] is JsonPrimitive && (e[0] as JsonPrimitive).isString) {
            Pt.Joint(e[0].jsonPrimitive.content, e[1].jsonPrimitive.float, e[2].jsonPrimitive.float)
        } else Pt.Abs(e[0].jsonPrimitive.float, e[1].jsonPrimitive.float)
        else -> Pt.Abs(0f, 0f)
    }

    private fun gear(o: JsonObject): Gear? {
        val ink = when (o["c"]?.jsonPrimitive?.content) { "gear2" -> Ink.GEAR2; "acc" -> Ink.ACCENT; else -> Ink.GEAR }
        val layer = when (o["z"]?.jsonPrimitive?.content) { "front" -> Layer.FRONT; "mid" -> Layer.MID; else -> Layer.BACK }
        fun f(k: String) = o[k]?.jsonPrimitive?.float ?: 0f
        fun pts(k: String) = o[k]?.jsonArray?.map { p -> p.jsonArray.let { Offset(it[0].jsonPrimitive.float, it[1].jsonPrimitive.float) } }
        return when (o["t"]?.jsonPrimitive?.content) {
            "line" -> Gear.Line(pt(o.getValue("a")), pt(o.getValue("b")), f("w"), ink, layer)
            "disc" -> Gear.Disc(pt(o.getValue("at")), f("r"), ink, layer)
            "ring" -> Gear.Ring(pt(o.getValue("at")), f("r"), f("w"), ink, layer)
            "kb" -> Gear.Kettlebell(pt(o.getValue("at")), f("r"), ink, layer)
            "rect" -> Gear.Rect(f("x"), f("y"), f("w"), f("h"), f("r"), ink, layer)
            "pill" -> Gear.Pill(pt(o.getValue("at")), f("w"), f("h"), ink, layer)
            "poly" -> Gear.Poly(pts("pts") ?: return null, pts("pts2"), ink, layer)
            else -> null
        }
    }
}

/**
 * Draws pictogram [name]. [animate] loops A ↔ B (eased); still images show frame B, the "working"
 * position, which reads best. [halo] must match the surface behind so near limbs separate cleanly.
 * Pictograms always face right: they show movements, not reading order.
 */
@Composable
fun Pictogram(
    name: String,
    modifier: Modifier = Modifier,
    animate: Boolean = false,
    figure: Color = Hyper.colors.accent,
    halo: Color = Hyper.colors.surface,
    durationMs: Int = 1500,
) {
    val context = LocalContext.current
    val art = remember(name) { ArtLibrary.get(context)[name] } ?: return
    val still = LocalInspectionMode.current || !animate || art.frames.size < 2
    val t = if (still) 1f else {
        val tr = rememberInfiniteTransition(label = "art")
        val v by tr.animateFloat(0f, 1f, infiniteRepeatable(tween(durationMs, easing = LinearEasing), RepeatMode.Reverse), label = "artT")
        // ease in-out with a short hold at both ends
        val x = ((v - 0.12f) / 0.76f).coerceIn(0f, 1f)
        x * x * (3 - 2 * x)
    }
    val c = Hyper.colors
    val gear = if (c.isDark) Color(0xFFB9BEC8) else Color(0xFF3C4048)
    val gear2 = if (c.isDark) Color(0xFF4A4F5A) else Color(0xFFC8CCD4)
    val floor = if (c.isDark) Color(0xFF2E323A) else Color(0xFFE4E6EB)
    val far = lerp(figure, halo, if (art.front) 0f else 0.55f)
    Canvas(modifier) {
        val s = minOf(size.width, size.height) / 100f
        val ox = (size.width - 100f * s) / 2f
        val oy = (size.height - 100f * s) / 2f
        val f = frame(art, t)
        translate(ox, oy) {
            scale(s, s, pivot = Offset.Zero) {
                drawArt(art, f, t, figure, far, gear, gear2, floor, halo)
            }
        }
    }
}

private fun lerp(a: Color, b: Color, t: Float) = Color(
    a.red + (b.red - a.red) * t, a.green + (b.green - a.green) * t, a.blue + (b.blue - a.blue) * t, a.alpha,
)

private fun frame(art: Art, t: Float): Map<String, Offset> {
    if (art.frames.size < 2) return art.frames.first()
    val a = art.frames[0]
    val b = art.frames[1]
    return a.mapValues { (k, p) -> val q = b[k] ?: p; Offset(p.x + (q.x - p.x) * t, p.y + (q.y - p.y) * t) }
}

private fun DrawScope.drawArt(
    art: Art, f: Map<String, Offset>, t: Float,
    fig: Color, far: Color, gear: Color, gear2: Color, floor: Color, halo: Color,
) {
    fun p(pt: Pt): Offset = when (pt) {
        is Pt.Abs -> Offset(pt.x, pt.y)
        is Pt.Joint -> (f[pt.name] ?: Offset.Zero) + Offset(pt.dx, pt.dy)
    }
    fun ink(i: Ink) = when (i) { Ink.GEAR -> gear; Ink.GEAR2 -> gear2; Ink.ACCENT -> fig }
    fun seg(a: Offset, b: Offset, w: Float, c: Color) = drawLine(c, a, b, w, StrokeCap.Round)
    fun gearLayer(l: Layer) = art.gear.filter { it.layer == l }.forEach { g ->
        val c = ink(g.ink)
        when (g) {
            is Gear.Line -> seg(p(g.a), p(g.b), g.w, c)
            is Gear.Disc -> drawCircle(c, g.r, p(g.at))
            is Gear.Ring -> drawCircle(c, g.r, p(g.at), style = Stroke(g.w))
            is Gear.Kettlebell -> {
                val at = p(g.at)
                drawCircle(c, g.r, at)
                drawOval(c, Offset(at.x - g.r * 0.62f, at.y - g.r * 1.75f), Size(g.r * 1.24f, g.r * 1.2f), style = Stroke(1.8f))
            }
            is Gear.Rect -> drawRoundRect(c, Offset(g.x, g.y), Size(g.w, g.h), CornerRadius(g.r))
            is Gear.Pill -> {
                val at = p(g.at)
                drawRoundRect(c, Offset(at.x - g.w / 2, at.y - g.h / 2), Size(g.w, g.h), CornerRadius(minOf(g.w, g.h) / 2))
            }
            is Gear.Poly -> {
                val pts = if (g.b != null) g.a.zip(g.b) { a, b -> Offset(a.x + (b.x - a.x) * t, a.y + (b.y - a.y) * t) } else g.a
                val path = Path().apply { pts.forEachIndexed { i, q -> if (i == 0) moveTo(q.x, q.y) else lineTo(q.x, q.y) }; close() }
                drawPath(path, c)
            }
        }
    }
    fun limb(names: List<String?>, base: String, width: Float, c: Color, withHalo: Boolean) {
        val pts = names.mapNotNull { n -> n?.let { f[it] } }.let { listOf(f[base]!!) + it }
        if (withHalo) pts.zipWithNext().forEach { (a, b) -> seg(a, b, width + 2.6f, halo) }
        pts.zipWithNext().forEachIndexed { i, (a, b) -> seg(a, b, if (i == 2) 5f else width, c) }
    }

    if (art.floor) seg(Offset(4f, 95f), Offset(96f, 95f), 1.2f, floor)
    gearLayer(Layer.BACK)
    val sBase2 = if ("s2" in f) "s2" else "s"
    val pBase2 = if ("p2" in f) "p2" else "p"
    limb(listOf("e2", "w2"), sBase2, 6.4f, far, false)
    limb(listOf("k2", "a2", "t2"), pBase2, 6.8f, far, false)
    gearLayer(Layer.MID)
    if ("s1" in f) {
        val path = Path().apply {
            moveTo(f["s1"]!!.x, f["s1"]!!.y); lineTo(f["s2"]!!.x, f["s2"]!!.y); lineTo(f["p2"]!!.x, f["p2"]!!.y); lineTo(f["p1"]!!.x, f["p1"]!!.y); close()
        }
        drawPath(path, fig)
        seg(f["s1"]!!, f["s2"]!!, 6f, fig)
        seg(f["p1"]!!, f["p2"]!!, 6f, fig)
    } else {
        seg(f["s"]!!, f["p"]!!, 9.5f, fig)
    }
    drawCircle(fig, 6.2f, f["h"]!!)
    val withHalo = !art.front
    limb(listOf("k1", "a1", "t1"), if ("p1" in f) "p1" else "p", 6.8f, fig, withHalo)
    limb(listOf("e1", "w1"), if ("s1" in f) "s1" else "s", 6.4f, fig, withHalo)
    gearLayer(Layer.FRONT)
}
